/**
 * Generates styles/_tokens.scss and tokens/tokens.ts from the Fluent UI v9 theme in tokens/theme.ts.
 *   npm run tokens          write the files
 *   npm run tokens:check    fail when the committed files differ from the theme
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  baseKnobs,
  baseTokens,
  darkKnobs,
  darkTokens,
  lightKnobs,
  lightTokens,
} from '../src/lib/tokens/theme';

const libRoot = resolve(dirname(fileURLToPath(import.meta.url)), '../src/lib');
const scssPath = resolve(libRoot, 'styles/_tokens.scss');
const tsPath = resolve(libRoot, 'tokens/tokens.ts');
const header = '// Generated by `npm run tokens` from tokens/theme.ts. Do not edit.\n';

const declarations = (set: Record<string, string | undefined>, indent: string) =>
  Object.entries(set)
    .map(([name, value]) => `${indent}--${name}: ${value};`)
    .join('\n');

const dark = { ...darkTokens, ...darkKnobs };
const scss = `${header}
:root {
${declarations({ ...baseTokens, ...baseKnobs, ...lightTokens, ...lightKnobs }, '  ')}
  color-scheme: light;
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme='light']) {
${declarations(dark, '    ')}
    color-scheme: dark;
  }
}

:root[data-theme='dark'] {
${declarations(dark, '  ')}
  color-scheme: dark;
}

@media (prefers-reduced-motion: reduce) {
  :root {
    --durationFaster: 0.01ms;
    --durationFast: 0.01ms;
    --durationNormal: 0.01ms;
    --durationSlow: 0.01ms;
    --durationUltraSlow: 0.01ms;
  }
}

@media (forced-colors: active) {
  :root {
    --colorStrokeFocus2: Highlight;
    --colorNeutralStroke1: CanvasText;
    --colorNeutralStroke2: CanvasText;
  }
}
`;

const names = [
  ...new Set([
    ...Object.keys(baseTokens),
    ...Object.keys(lightTokens),
    ...Object.keys(baseKnobs),
    ...Object.keys(lightKnobs),
    ...Object.keys(darkKnobs),
  ]),
];
const camel = (name: string) => name.replace(/-([a-z0-9])/g, (_, c: string) => c.toUpperCase());
const ts = `${header}
/** CSS variable references for every 6ixstack token, by name. */
export const tokens = {
${names.map((n) => `  ${camel(n)}: 'var(--${n})',`).join('\n')}
} as const;

export type TokenName = keyof typeof tokens;
`;

if (process.argv.includes('--check')) {
  const stale = [
    [scssPath, scss],
    [tsPath, ts],
  ].filter(([path, content]) => {
    try {
      return readFileSync(path, 'utf8') !== content;
    } catch {
      return true;
    }
  });
  if (stale.length) {
    console.error(`Tokens are out of date: ${stale.map(([p]) => p).join(', ')}. Run npm run tokens.`);
    process.exit(1);
  }
  console.log('Tokens are up to date.');
} else {
  writeFileSync(scssPath, scss);
  writeFileSync(tsPath, ts);
  console.log(`Wrote ${scssPath} and ${tsPath}`);
}
